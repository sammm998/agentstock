        "2. What do they use today (direct competitors, substitutes, doing nothing)?",
        "3. What do comparable offers cost, and what do buyers complain about in reviews?",
        "4. Which channels reach these buyers at a cost you can afford?",
        "5. Are there rules that apply (product safety, consumer law, platform policies, IP)?",
        "## Evidence to collect",
        "- 10+ real conversations or survey responses from target buyers",
        "- 5 competitor offers with price, positioning and review themes",
        "- Search and marketplace demand signals for your main keywords",
        "## Decision rule",
        "Proceed only if you can name a specific audience, a reachable channel and a price that covers costs with margin.",
