export interface ToolContext {
  db: Queryable;
  ownerId: string;
  missionId: string;
  kind: MissionKind;
  title: string;
  brief: string;
  region: string;
  priceCents: number;
  /** Latest artifact content produced by each earlier task, keyed by task key. */
  inputs: Record<string, string>;
}

export interface ToolResult {
  artifact: { kind: string; title: string; content: string };
  /** Actual cost, which must not exceed the reserved upper bound. */
  costCents: number;
  message: string;
}

export type ToolOutcome = { ok: true; result: ToolResult } | { ok: false; blocked: true; reason: string } | { ok: false; blocked: false; error: string };

